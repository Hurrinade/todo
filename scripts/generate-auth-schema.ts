import { mkdir, writeFile } from "node:fs/promises";
import { apiKey } from "@better-auth/api-key";
import { getAuthTables } from "better-auth/db";

import { options } from "../node_modules/@convex-dev/better-auth/src/auth-options";
import { createSchema } from "../node_modules/@convex-dev/better-auth/src/client/create-schema";

// Keep every table from the pinned component, including existing users and sessions.
// These source imports are confined to this local generator, never the runtime.
const tables = getAuthTables({
  ...options,
  plugins: [...(options.plugins ?? []), apiKey()],
});
const { code } = await createSchema({ tables });
await mkdir("convex/betterAuth", { recursive: true });
await writeFile(
  "convex/betterAuth/generatedSchema.ts",
  code.replace(
    /\/\*\*[\s\S]*?\*\//,
    "/** Generated by bun --no-env-file scripts/generate-auth-schema.ts. Do not edit manually. */",
  ),
);
