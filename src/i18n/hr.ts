const pluralRules = new Intl.PluralRules("hr");

// Croatian has three count forms: 1 porcija, 2 porcije, 5 porcija.
function count(total: number, one: string, few: string, other: string) {
  const rule = pluralRules.select(total);

  return `${total} ${rule === "one" ? one : rule === "few" ? few : other}`;
}

